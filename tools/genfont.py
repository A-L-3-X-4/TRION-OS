#!/usr/bin/env python3
"""Generate kernel/font8x16.c (CP437, 8x16, 256 glyphs) from GNU Unifont's unifont.hex.

    tools/genfont.py [/usr/share/unifont/unifont.hex] > kernel/font8x16.c

Unifont is dual-licensed GPLv2+ (font embedding exception) / SIL OFL 1.1; the glyph bitmaps are
data, the kernel just blits them. Debian: `apt install unifont`.
"""
import sys

CTRL = "\0☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼"
path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/unifont/unifont.hex"

hexmap = {}
for line in open(path, encoding="ascii"):
    cp, _, bits = line.strip().partition(":")
    if len(bits) == 32:
        hexmap[int(cp, 16)] = bytes.fromhex(bits)

def uni(b):
    if b < 0x20: return ord(CTRL[b])
    if b == 0x7F: return 0x2302
    return ord(bytes([b]).decode("cp437"))

missing = []
out = ["/* generated by tools/genfont.py from GNU Unifont (GPLv2+ w/ font exception, or SIL OFL 1.1): CP437, 8x16 */",
       "#include <stdint.h>", "",
       "const uint8_t font8x16[256][16] = {"]
for b in range(256):
    u = uni(b)
    g = hexmap.get(u, bytes(16))
    if u not in hexmap and b != 0 and b != 0xFF:
        missing.append(hex(b))
    out.append("    {%s}," % ",".join("0x%02X" % x for x in g))
out.append("};")
print("\n".join(out))
if missing:
    print("warning: no 8x16 glyph for bytes", " ".join(missing), file=sys.stderr)
